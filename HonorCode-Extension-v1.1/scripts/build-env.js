// scripts/build-env.js
// Chrome/Edge extensions cannot read a .env file while running, so this small
// script does it ahead of time (a "build step"). It:
//   1. Reads .env (or the file you pass as the first argument).
//   2. Checks every value and stops with a clear message if one is wrong.
//   3. Writes env.js, which config.js imports.
//   4. Sets manifest.json -> host_permissions to match API_BASE_URL.
//
// Usage:   node scripts/build-env.js              (uses .env)
//          node scripts/build-env.js .env.production
// Needs only Node.js. No packages to install.

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");                    // the extension folder
const envPath = path.join(root, process.argv[2] || ".env"); // which settings file to read

// Stops the script with a readable message.
function fail(msg) {
  console.error("\nbuild-env: " + msg + "\n");
  process.exit(1);
}

if (!fs.existsSync(envPath)) {
  fail(`${path.basename(envPath)} not found. Copy .env.example to .env and edit it first.`);
}

// ---- 1. Read the file into a plain object ----
const raw = {};
for (const line of fs.readFileSync(envPath, "utf8").split(/\r?\n/)) {
  const t = line.trim();
  if (!t || t.startsWith("#")) continue;         // skip blank lines and comments
  const eq = t.indexOf("=");
  if (eq === -1) continue;                        // skip lines that are not KEY=VALUE
  let value = t.slice(eq + 1).trim();
  const quoted = (value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"));
  if (quoted && value.length >= 2) value = value.slice(1, -1); // remove surrounding quotes
  raw[t.slice(0, eq).trim()] = value;
}

// ---- 2. Typed readers that fall back to a default and validate ----
function readString(key, fallback) {
  const v = raw[key] !== undefined && raw[key] !== "" ? raw[key] : fallback;
  if (v === undefined) fail(`${key} is required.`);
  return v;
}
function readBool(key, fallback) {
  const v = raw[key] === undefined || raw[key] === "" ? fallback : raw[key].toLowerCase();
  if (v === true || v === "true") return true;
  if (v === false || v === "false") return false;
  return fail(`${key} must be true or false (got "${raw[key]}").`);
}
function readNumber(key, fallback) {
  const v = raw[key] === undefined || raw[key] === "" ? fallback : Number(raw[key]);
  if (!Number.isFinite(v) || v <= 0) fail(`${key} must be a positive number (got "${raw[key]}").`);
  return v;
}

// ---- 3. Build and check the values ----
let apiBase = readString("API_BASE_URL").replace(/\/+$/, ""); // remove any trailing slash
let apiUrl;
try { apiUrl = new URL(apiBase); } catch { fail(`API_BASE_URL is not a valid URL ("${apiBase}").`); }
const isLocal = apiUrl.hostname === "localhost" || apiUrl.hostname === "127.0.0.1";
if (apiUrl.protocol !== "https:" && !(apiUrl.protocol === "http:" && isLocal)) {
  fail("API_BASE_URL must use https:// (plain http:// is only allowed for localhost).");
}

const ENV = {
  API_BASE_URL: apiBase,
  QUIZ_URL_PREFIX: readString("QUIZ_URL_PREFIX", "https://docs.google.com/forms/"),
  ALLOW_ANY_PAGE_AS_QUIZ: readBool("ALLOW_ANY_PAGE_AS_QUIZ", false),
  ALLOW_MANUAL_STOP: readBool("ALLOW_MANUAL_STOP", true),
  BATCH_SIZE: readNumber("BATCH_SIZE", 20),
  FLUSH_INTERVAL_MS: readNumber("FLUSH_INTERVAL_MS", 15000),
  REQUEST_TIMEOUT_MS: readNumber("REQUEST_TIMEOUT_MS", 10000),
  HEARTBEAT_MINUTES: readNumber("HEARTBEAT_MINUTES", 0.5),
  MAX_SESSION_HOURS: readNumber("MAX_SESSION_HOURS", 6)
};

// Guard rail: a build with the "any page counts as the quiz" test switch on
// is flagged so it is not shipped to students by accident.
if (ENV.ALLOW_ANY_PAGE_AS_QUIZ) {
  console.warn("build-env: WARNING ALLOW_ANY_PAGE_AS_QUIZ is true. Use this for testing only.");
}

// ---- 4. Write env.js (read by config.js) ----
const header = "// AUTO-GENERATED by scripts/build-env.js from " + path.basename(envPath) + ".\n" +
               "// Do not edit by hand and do not commit (it is in .gitignore).\n";
fs.writeFileSync(path.join(root, "env.js"), header + "export const ENV = " + JSON.stringify(ENV, null, 2) + ";\n");

// ---- 5. Keep manifest.json's host_permissions in step with API_BASE_URL ----
// Without this the extension is not allowed to call the backend.
const manifestPath = path.join(root, "manifest.json");
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
manifest.host_permissions = [apiUrl.origin + "/*"];
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

console.log(`build-env: wrote env.js and set host_permissions to ${apiUrl.origin}/*`);
